const opentype = require('opentype.js');
const fs = require('fs');
const path = require('path');

const fontPath = path.resolve(__dirname, '../../../PoetsenOne-Regular.ttf');
const buf = fs.readFileSync(fontPath);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const fontSize = 100;
const chars = 'noroset'.split('');

let x = 0;
const glyphPaths = [];
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;

for (let i = 0; i < chars.length; i++) {
  const g = font.charToGlyph(chars[i]);
  const p = g.getPath(x, 100, fontSize);
  const bb = p.getBoundingBox();
  if (bb.x1 < minX) minX = bb.x1;
  if (bb.y1 < minY) minY = bb.y1;
  if (bb.x2 > maxX) maxX = bb.x2;
  if (bb.y2 > maxY) maxY = bb.y2;
  glyphPaths.push({ i, char: chars[i], p });

  let adv = g.advanceWidth * (fontSize / font.unitsPerEm);
  if (i < chars.length - 1) {
    const nextG = font.charToGlyph(chars[i + 1]);
    adv += font.getKerningValue(g, nextG) * (fontSize / font.unitsPerEm);
  }
  x += adv;
}

// Shift all path commands so minX=0, minY=0
const noroCommands = [];
const setCommands = [];

glyphPaths.forEach(({ i, p }) => {
  p.commands.forEach((cmd) => {
    const c = Object.assign({}, cmd);
    if ('x' in c) c.x = +(c.x - minX).toFixed(2);
    if ('y' in c) c.y = +(c.y - minY).toFixed(2);
    if ('x1' in c) c.x1 = +(c.x1 - minX).toFixed(2);
    if ('y1' in c) c.y1 = +(c.y1 - minY).toFixed(2);
    if ('x2' in c) c.x2 = +(c.x2 - minX).toFixed(2);
    if ('y2' in c) c.y2 = +(c.y2 - minY).toFixed(2);
    if (i < 4) noroCommands.push(c);
    else setCommands.push(c);
  });
});

const noroPath = new opentype.Path();
noroPath.commands = noroCommands;
const setPath = new opentype.Path();
setPath.commands = setCommands;

const dNoro = noroPath.toPathData(2);
const dSet = setPath.toPathData(2);

const width = +(maxX - minX).toFixed(2);
const height = +(maxY - minY).toFixed(2);

console.log('Poetsen One width x height:', width, 'x', height);
console.log('dNoro length:', dNoro.length);
console.log('dSet length:', dSet.length);

// Colors requested:
// Two colors: gentle professional gray for 'noro', blue for 'set', flat colors.
const NORO_COLOR = '#64748B'; // Gentle, professional slate gray (slate-500)
const SET_COLOR = '#2563EB';  // Clean, vibrant flat tech blue (blue-600)

// Save pure vector SVG with flat colors and theme adaptability
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" aria-label="noroset">
  <style>
    .noro { fill: ${NORO_COLOR}; }
    .set { fill: ${SET_COLOR}; }
    @media (prefers-color-scheme: dark) {
      .noro { fill: #94A3B8; }
      .set { fill: #38BDF8; }
    }
  </style>
  <path class="noro" d="${dNoro}" fill="${NORO_COLOR}" />
  <path class="set" d="${dSet}" fill="${SET_COLOR}" />
</svg>
`;

const publicLogoPath = path.resolve(__dirname, '../public/logo.svg');
const publicImagesLogoPath = path.resolve(__dirname, '../public/images/logo.svg');
fs.writeFileSync(publicLogoPath, svg);
fs.writeFileSync(publicImagesLogoPath, svg);
console.log('Saved public/logo.svg and public/images/logo.svg!');

// Output TSX constants
const brandPathsFile = path.resolve(__dirname, '../src/components/brand-paths.ts');
const componentCode = `// Autogenerated pure vector SVG paths from authentic Poetsen One font
export const NORO_PATH = '${dNoro}';
export const SET_PATH = '${dSet}';
export const LOGO_WIDTH = ${width};
export const LOGO_HEIGHT = ${height};
export const DEFAULT_NORO_COLOR = '${NORO_COLOR}';
export const DEFAULT_SET_COLOR = '${SET_COLOR}';
`;
fs.writeFileSync(brandPathsFile, componentCode);
console.log('Saved src/components/brand-paths.ts!');
